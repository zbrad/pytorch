#!/bin/bash
# tuned/build.sh <variant> — build pytorch from source for a single GPU variant
# (gb10/rtx40/rtx50) only, single-arch, and assemble the wheel, under tuned/build/cu<ver>/
# (see env.sh). This is the real, multi-hour compile step.
#
#   CUDA_TAG=cu134 bash tuned/build.sh gb10
#
# Stage order: build.sh -> full_test.sh -> package.sh -> smoke_test.sh -> (review and commit the
# release notes) -> release.sh (docs/ARCHITECTURE.md in zbrad/tuned-common).
#
# The output is the UNSTAMPED wheel in tuned/build/<cuda-tag>/wheel/, with the release label baked in
# (E4): the date label is allocated here, written to <build>/release-label, and compiled into
# torch.__version__. full_test.sh tests exactly this wheel; package.sh stamps a staged copy of it
# and never touches it, so the wheel stays older than the test log. build-commit records the source
# commit it came from (torch/version.py cannot: it is regenerated by every build).
#
# Uses the modern PEP 517 flow (pytorch's own setup.py is now just a deprecation shim, see
# setup.py's own DEPRECATION_NOTICE): `python -m build --wheel --no-isolation`, not `python setup.py`.
# There is no editable install: nothing tests or ships a tree that is not a wheel.
set -euo pipefail

GPU_TUNED_ARG_VARIANT="$1"
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "${REPO_ROOT}"

# shellcheck source=env.sh
source "${REPO_ROOT}/tuned/env.sh" "${GPU_TUNED_ARG_VARIANT}"

command -v python3 &>/dev/null || { echo "ERROR: python3 not found on PATH." >&2; exit 1; }

VENV_DIR="${GPU_TUNED_VENV_DIR}"
# Create or reuse (verified), activate, upgrade pip, current setuptools: one shared setup (C9, tuned-common).
gpu_tuned_setup_build_venv "${VENV_DIR}" "${REPO_ROOT}" || exit 1

echo "=========================================="
echo "Building pytorch for ${GPU_TUNED_HW_LABEL} only"
echo "=========================================="
echo "TORCH_CUDA_ARCH_LIST: ${TORCH_CUDA_ARCH_LIST}"
echo "USE_CUDA:             ${USE_CUDA}"
[ -n "${USE_KLEIDIAI_SME:-}" ] && echo "USE_KLEIDIAI_SME:      ${USE_KLEIDIAI_SME}"
echo "CUDA_HOME:            ${CUDA_HOME:-<unset>}"
echo "MAX_JOBS:              ${MAX_JOBS}"
echo "Python:                $(python3 --version)"
echo "Git commit:             $(git rev-parse --short HEAD 2>/dev/null || echo unknown)"
echo ""

echo "Installing build-time requirements..."
pip install --upgrade pip
[ -f requirements.txt ] && pip install -r requirements.txt
pip install "typing-extensions>=4.10.0" "scikit-build-core>=1.0" build wheel
# The current setuptools, installed last (C8, tuned-common): requirements.txt (upstream) can cap it.
gpu_tuned_install_setuptools || exit 1

# third_party/nccl is a nested checkout, not a tracked git submodule of
# this repo (third_party/nccl/ is gitignored here) -- a local fix there
# is otherwise invisible to `git status` and silently lost on a fresh
# clone or submodule reset. This applies tuned/patches/nccl-ldmc-arch-gate.patch
# (checked in, so it IS durable/reproducible) every build, loudly, so
# it's never silently missing: without it, NCCL's device/Makefile
# unconditionally compiles sm_100f/sm_100a "LDMC" multicast device code
# into every build with CUDA >= 12.7 regardless of TORCH_CUDA_ARCH_LIST,
# breaking this fleet's single-arch invariant with a fat binary (caught
# by gpu_tuned_verify_arch downstream in package.sh, but this fixes the
# root cause instead of just detecting it). Filed upstream:
# https://github.com/NVIDIA/nccl/issues/2420 -- remove this patch and
# this whole step once that's fixed there. See
# tuned/patches/nccl-ldmc-arch-gate.patch for the full rationale.
NCCL_MAKEFILE="${REPO_ROOT}/third_party/nccl/src/device/Makefile"
NCCL_PATCH="${REPO_ROOT}/tuned/patches/nccl-ldmc-arch-gate.patch"
echo "=========================================="
echo "NCCL LDMC arch-gate patch check"
echo "=========================================="
if [[ -n "${GPU_TUNED_NCCL_DIR:-}" ]]; then
    echo "SKIP: prebuilt NCCL (GPU_TUNED_NCCL_DIR=${GPU_TUNED_NCCL_DIR}); third_party/nccl is not used."
elif [[ ! -f "${NCCL_MAKEFILE}" ]]; then
    echo "WARNING: ${NCCL_MAKEFILE} not found (third_party/nccl not yet" >&2
    echo "  checked out) -- cannot apply the NCCL LDMC arch-gate patch this run." >&2
    echo "  gpu_tuned_verify_arch in package.sh will still catch a fat sm_100" >&2
    echo "  binary if NCCL's build ends up unpatched -- but if it does, rerun" >&2
    echo "  this script (third_party/nccl should exist by then) rather than" >&2
    echo "  publishing an unverified wheel." >&2
elif grep -q "zbrad/pytorch tuned-builds: compile LDMC" "${NCCL_MAKEFILE}"; then
    echo "OK: NCCL LDMC arch-gate patch already applied."
else
    echo "APPLYING LOCAL PATCH: NCCL LDMC/multicast FP8 kernel gencode fix" >&2
    echo "  (fat sm_100+${GPU_TUNED_TORCH_ARCH} binary fix -- see" >&2
    echo "  tuned/patches/nccl-ldmc-arch-gate.patch for the full story)." >&2
    if patch -p1 -d "${REPO_ROOT}/third_party/nccl" < "${NCCL_PATCH}"; then
        echo "OK: NCCL LDMC arch-gate patch applied."
    else
        echo "ERROR: NCCL LDMC arch-gate patch FAILED to apply -- upstream NCCL" >&2
        echo "  likely changed src/device/Makefile since this patch was written." >&2
        echo "  Without this fix, the build will silently embed unreachable" >&2
        echo "  sm_100 device code (dead on this GPU, but breaks the single-arch" >&2
        echo "  invariant gpu_tuned_verify_arch checks). Re-derive the patch by" >&2
        echo "  hand against the new Makefile before proceeding -- do not skip" >&2
        echo "  this and hope package.sh's verify catches it; fix it here instead." >&2
        exit 1
    fi
fi
echo ""

# Every shared object the wheel ships takes the -tuned name (file name, SONAME, every NEEDED), set on
# the CMake targets through tuned-common's generated include (docs/ARCHITECTURE.md F4). The Python and
# C++ code that loads or links them by name carries the matching -tuned strings (tuned/repo.env lists
# those fork edits). The wheel's Python extension module _C keeps its name: a module name cannot hold a hyphen.
SO_NAMES_CMAKE="${GPU_TUNED_BUILD_ROOT}/so_names.cmake"
gpu_tuned_so_names_cmake "${SO_NAMES_CMAKE}"
export CMAKE_ARGS="-DCMAKE_PROJECT_TOP_LEVEL_INCLUDES=${SO_NAMES_CMAKE} -DTUNED_SO_TARGETS=${GPU_TUNED_SO_TARGETS} ${CMAKE_ARGS:-}"

gpu_tuned_assert_cmake_cache_consistent

# Release label, allocated once, here (E3/E4): HEAD's UTC commit date plus the lowest unused
# sequence among this repo's release tags (GPU_TUNED_LABEL_SEQ=0 skips the tag lookup for a dev
# build that will never be published). BASE_VERSION is upstream's version.txt with any PEP 440
# pre-release suffix (a0/b0/rc1) stripped, so the wheel still satisfies torch==<upstream> pins.
BASE_VERSION="$(sed -E 's/[a-z]+[0-9]+$//' "${REPO_ROOT}/version.txt" | tr -d '[:space:]')"
PYTORCH_LOCAL_VERSION="$(gpu_tuned_build_local_version "${GPU_TUNED_VARIANT}" "${REPO_ROOT}")" || exit 1
[[ "${PYTORCH_LOCAL_VERSION}" == *".cu${CUDA_VERSION_COMPACT}."* ]] || {
    echo "ERROR: label ${PYTORCH_LOCAL_VERSION} disagrees with ${CUDA_TAG} (from ${CUDA_HOME}); nvcc and the toolkit definition must report the same release." >&2
    exit 1
}
export PYTORCH_BUILD_VERSION="${BASE_VERSION}+${PYTORCH_LOCAL_VERSION}"
export PYTORCH_BUILD_NUMBER=1
echo "PYTORCH_BUILD_VERSION: ${PYTORCH_BUILD_VERSION}"

# Remove the previous build's markers first: they are rewritten only if this build succeeds.
rm -f "${GPU_TUNED_BUILD_ROOT}/build-commit" "${GPU_TUNED_BUILD_ROOT}/release-label"
mkdir -p "${GPU_TUNED_WHEEL_DIR}"
rm -f "${GPU_TUNED_WHEEL_DIR}"/torch-*.whl

echo "Building pytorch (this will take a long time)..."
python3 -m build --wheel --no-isolation --outdir "${GPU_TUNED_WHEEL_DIR}"

WHEEL="$(ls "${GPU_TUNED_WHEEL_DIR}"/torch-*.whl 2>/dev/null | head -1)"
[[ -n "${WHEEL}" ]] || { echo "ERROR: no wheel found in ${GPU_TUNED_WHEEL_DIR}" >&2; exit 1; }
[[ "$(basename "${WHEEL}")" == "torch-${PYTORCH_BUILD_VERSION}-"* ]] || {
    echo "ERROR: built wheel $(basename "${WHEEL}") does not carry PYTORCH_BUILD_VERSION=${PYTORCH_BUILD_VERSION}." >&2
    exit 1
}
gpu_tuned_check_wheel_label "${WHEEL}"
echo "Built wheel: $(basename "${WHEEL}") ($(du -sh "${WHEEL}" | awk '{print $1}'))"

gpu_tuned_assert_versioned_runpath "${GPU_TUNED_CMAKE_DIR}/lib/libtorch_cuda-tuned.so"

# Written last: their presence means the build finished. full_test.sh and package.sh (H6) read the
# commit; package.sh and release.sh read the label and never recompute it.
BUILD_COMMIT="$(git rev-parse HEAD)"
[[ -z "$(git status --porcelain --untracked-files=no)" ]] || BUILD_COMMIT="${BUILD_COMMIT}-dirty"
printf '%s\n' "${PYTORCH_LOCAL_VERSION#*.cu${CUDA_VERSION_COMPACT}.}" > "${GPU_TUNED_BUILD_ROOT}/release-label"
printf '%s\n' "${BUILD_COMMIT}" > "${GPU_TUNED_BUILD_ROOT}/build-commit"

echo ""
echo "=========================================="
echo "Build complete (${GPU_TUNED_HW_LABEL})."
echo "=========================================="
echo "Wheel:        ${WHEEL}"
echo "Label:        $(cat "${GPU_TUNED_BUILD_ROOT}/release-label")"
echo "Build commit: ${BUILD_COMMIT}"
echo "Next: bash tuned/full_test.sh ${GPU_TUNED_VARIANT}"
